"""Author public English alignment inputs with known placement, not phonetic truth."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
import wave

ROOT=Path(__file__).resolve().parents[1]


def write_wave(path, data):
    with wave.open(str(path),'wb') as stream:
        stream.setnchannels(1);stream.setsampwidth(2);stream.setframerate(16000);stream.writeframes(data)


def main(args):
    import numpy as np
    from PIL import Image, ImageDraw, ImageFont
    output=args.output.resolve()
    assert output.is_relative_to(ROOT/'docs/assets') and not output.exists()
    output.mkdir(parents=True)
    ffmpeg=shutil.which('ffmpeg');assert ffmpeg
    words=['RED','BLUE','GREEN','RED','BLUE','GREEN']
    raw={};records=[]
    for word in dict.fromkeys(words):
        path=output/(word.lower()+'-flite-raw.wav')
        command=[ffmpeg,'-v','error','-nostdin','-n','-f','lavfi','-i',f'flite=text={word.lower()}:voice=slt',
                 '-ar','16000','-ac','1','-c:a','pcm_s16le',str(path)]
        subprocess.run(command,check=True,capture_output=True)
        with wave.open(str(path),'rb') as stream:data=np.frombuffer(stream.readframes(stream.getnframes()),dtype='<i2').copy()
        active=np.flatnonzero(np.abs(data.astype(np.int32))>=32)
        assert active.size
        a,b=int(active[0]),int(active[-1])+1
        raw[word]=data[a:b].tobytes()
        records.append({'word':word,'source':path.name,'trim_first_sample':a,'trim_end_sample':b,
                        'criterion':'first/last absolute signed PCM >= 32; not phonetic labels','command':command})
    pieces=[bytes(8000*2)]
    cursor=8000
    truth=[]
    for word in words:
        data=raw[word];count=len(data)//2
        truth.append({'word':word,'start_sample':cursor,'end_sample':cursor+count})
        pieces.extend([data,bytes(8000*2)])
        cursor+=count+8000
    pcm=b''.join(pieces)
    write_wave(output/'input.wav',pcm)
    # A source longer than 30 seconds crosses real model inference windows.
    copies=6
    write_wave(output/'input-long.wav',pcm*copies)
    (output/'transcript.txt').write_text(' '.join(words),encoding='utf-8')
    (output/'transcript-long.txt').write_text(' '.join(words*copies),encoding='utf-8')
    font=ROOT/'docs/assets/clip-windows-20261018/agent-grid-cc0.ttf'
    shutil.copyfile(font,output/'font.ttf')
    image=Image.new('RGB',(1280,720),(13,26,43));draw=ImageDraw.Draw(image)
    face=ImageFont.truetype(str(font),32)
    draw.text((44,40),'OFFLINE CTC ALIGNMENT',font=face,fill=(230,240,250))
    draw.text((44,100),'LOCAL SLT VOICE / AUTHORED WORD BLOCKS',font=ImageFont.truetype(str(font),20),fill=(115,185,215))
    samples=np.frombuffer(pcm,dtype='<i2')
    for x in range(60,1220):
        a=(x-60)*len(samples)//1160;b=(x-59)*len(samples)//1160
        maximum=int(np.max(np.abs(samples[a:max(a+1,b)].astype(np.int32))))
        height=maximum*150//32768
        draw.line((x,345-height,x,345+height),fill=(57,192,218))
    image.save(output/'background.png')
    duration=len(pcm)/32000
    command=[ffmpeg,'-v','error','-nostdin','-n','-loop','1','-i',str(output/'background.png'),'-i',str(output/'input.wav'),
        '-t',str(duration),'-r','30','-c:v','libx264','-crf','18','-pix_fmt','yuv420p','-c:a','aac','-b:a','192k',str(output/'input.mp4')]
    subprocess.run(command,check=True,capture_output=True)
    report={'format':'ctc-authored-word-blocks-v1','sample_rate':16000,'samples':len(pcm)//2,
        'duration_seconds':duration,'words':truth,'long_copies':copies,'long_samples':len(pcm)//2*copies,
        'word_sources':records,'video_command':command,'quality_goal':{'reference':'known authored trimmed word blocks, not phonetic boundaries',
        'boundary_error_seconds_max':2/30,'predeclared_fps':30},'generator_sha256':hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        'rights':{'authored_text_and_placement':'CC0-1.0','font':'original project grid font CC0-1.0',
        'speech':'generated by installed FFmpeg flite voice=slt; upstream Flite/CMU permissive license attribution retained in docs/third-party',
        'not_a_human_voice_clone':True},'static_review':False,'continuous_playback_review':False,'listening_review':False,
        'files':{p.name:{'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for p in sorted(output.iterdir()) if p.is_file()}}
    (output/'input-provenance.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'duration_seconds':duration,'long_duration_seconds':duration*copies,'words':len(words),'files':len(report['files'])}))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,required=True);main(p.parse_args())
