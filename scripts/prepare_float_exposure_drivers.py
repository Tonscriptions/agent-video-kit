"""Adapt byte-verified local media/install procedures for the exposure candidate."""
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARENT = ROOT.parent/'float-preview-lab-20261022'
REL = ROOT/'docs/validation/evidence/float-exposure-20261022-lab'


def sha(p):
    return 'sha256:'+hashlib.sha256(p.read_bytes()).hexdigest()


def once(text, old, new):
    assert text.count(old) == 1, (old, text.count(old))
    return text.replace(old,new)


def main():
    source = PARENT/'scripts/smoke_float_preview_media.py'
    source_receipt = json.loads((PARENT/'docs/validation/evidence/float-preview-20261022-lab/media-r1/verification.json').read_bytes())
    assert source_receipt['script_sha256'] == sha(source)
    text = source.read_text('utf8').replace('float-preview-20261022','float-exposure-20261022')
    text = text.replace('Original native float timeline preview demo','Original native linear Float32 exposure demo')
    text = text.replace('float_preview_media','float_exposure_media')
    text = once(text, "                q = np.rint(frame", "                frame[:, :, :3] *= .6\n                q = np.rint(frame")
    start = text.index('        overlay = copy.deepcopy(base);')
    end = text.index('        save_project(project_root, p)', start)
    text = text[:start]+"        base['effects'] = [{'type': 'exposure', 'parameters': {'amount': 1, 'black': .003}}]\n"+text[end:]
    anchor = "        planes = np.frombuffer(raw_float, '<f4').reshape(14, 4, h, w)"
    addition = '''        # Independent encoded-source -> linear -> exposure calculation over
        # every selected actual CLI Float32 pixel; no product color/effect helper.
        source_planes = np.frombuffer(raw.read_bytes(), '<u2').reshape(count, 4, h, w)
        original_rgb = np.moveaxis(source_planes[3:17, [2,0,1]], 1, -1).astype(np.float32)/np.float32(65535)
        encoded64 = original_rgb.astype(np.float64)
        linear32 = np.where(encoded64 < .081, encoded64/4.5, ((encoded64+.099)/1.099)**(1/.45)).astype(np.float32)
        black32 = np.float32(.003)
        scale32 = np.float32(1/float(np.abs(np.float32(np.float32(.5)-black32))))
        expected_rgb = (linear32-black32)*scale32
        actual_rgb = np.moveaxis(planes[:,[2,0,1]],1,-1)
        error = float(np.max(np.abs(actual_rgb-expected_rgb)))
        check('all selected actual CLI linear RGB match independent exposure oracle', error <= 3e-7,
            maximum_linear_absolute_error=error, compared_RGB_values=int(actual_rgb.size))
        check('all selected exposure alpha bits remain opaque', np.all(planes[:,3] == 1))
        record['exposure_oracle'] = {'amount':1, 'black':float(black32), 'scale':float(scale32),
            'maximum_linear_absolute_error':error, 'RGB_values':int(actual_rgb.size), 'input_transfer':'bt709-oetf',
            'working_domain':'linear', 'integer_intermediate':False, 'natural_media_or_HDR_acceptance':False}
        (assets/'author-project.json').write_text(json.dumps(authored,ensure_ascii=False,indent=2)+'\\n',encoding='utf8',newline='\\n')
        (assets/'rights-ledger.json').write_text(json.dumps(ledger,ensure_ascii=False,indent=2)+'\\n',encoding='utf8',newline='\\n')
        (assets/'LICENSE.txt').write_text('Synthetic picture and sine-wave audio generated by smoke_float_exposure_media.py.\\nDedicated to CC0-1.0. No third-party footage, voice, music, font, model or likeness.\\n',encoding='utf8',newline='\\n')
'''
    text = once(text,anchor,anchor+'\n'+addition.rstrip())
    text = text.replace('300 source inputs unchanged','302 source inputs unchanged').replace("len(record['frozen_before']) == 300", "len(record['frozen_before']) == 302")
    text = text.replace('passed-public-CLI-original-edited-and-native-float-previews','passed-public-CLI-linear-exposure-and-native-float-previews')
    text = text.replace('EDITED / CLI Float32','EXPOSURE +1 EV / CLI').replace('ACTUAL CLI PREVIEW / Float32','EXPOSURE +1 EV / PREVIEW')
    ast.parse(text)
    media_target = ROOT/'scripts/smoke_float_exposure_media.py'
    assert not media_target.exists()
    media_target.write_text(text,encoding='utf8',newline='\n')
    installer = PARENT/'scripts/verify_float_preview_install.py'
    accepted = json.loads((PARENT/'docs/validation/evidence/float-preview-20261022-lab/installed-r1/verification.json').read_bytes())
    assert accepted['generator_sha256'] == sha(installer)
    text = installer.read_text('utf8')
    for old,new in [('float-preview-20261022','float-exposure-20261022'),
        ('smoke_float_preview_media.py','smoke_float_exposure_media.py'),
        ('passed-public-CLI-original-edited-and-native-float-previews','passed-public-CLI-linear-exposure-and-native-float-previews'),
        ('180','181'),('300','302'),('260','274'),
        ("standard['methods'] == 57", "standard['methods'] == 74"),('actual native 57 methods','actual native 74 methods')]:
        assert old in text, old
        text=text.replace(old,new)
    text=once(text,"'test_timeline_preview', 'test_float_preview']", "'test_timeline_preview', 'test_float_preview', 'test_float_exposure']")
    text=once(text,"native_float_preview_integrated=True, default_backend_migrated=False", "native_float_preview_integrated=True, native_float_exposure_integrated=True, default_backend_migrated=False")
    ast.parse(text)
    install_target=ROOT/'scripts/verify_float_exposure_install.py';assert not install_target.exists()
    install_target.write_text(text,encoding='utf8',newline='\n')
    receipt=REL/'drivers-r1.json';assert not receipt.exists()
    receipt.write_text(json.dumps({'status':'prepared-byte-verified-parent-drivers',
        'parent_media_sha256':sha(source),'media_sha256':sha(media_target),
        'parent_install_sha256':sha(installer),'install_sha256':sha(install_target),
        'expected_installed_methods':274,'expected_resources':181,'expected_product_inputs':302,
        'executed':False},ensure_ascii=False,indent=2)+'\n',encoding='utf8',newline='\n')
    print(receipt)


if __name__=='__main__':main()
